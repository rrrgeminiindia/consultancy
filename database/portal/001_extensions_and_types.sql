BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

SET TIME ZONE 'UTC';

CREATE TYPE platform_role AS ENUM ('OWNER_ADMIN', 'STANDARD', 'SUPPORT');
CREATE TYPE account_status AS ENUM ('INVITED', 'ACTIVE', 'SUSPENDED', 'DEACTIVATED');
CREATE TYPE instance_status AS ENUM (
  'PROVISIONING',
  'ACTIVE',
  'READ_ONLY',
  'SUSPENDED',
  'DETACHING',
  'DETACHED',
  'DECOMMISSIONED'
);
CREATE TYPE instance_access_status AS ENUM ('ACTIVE', 'SUSPENDED', 'REVOKED');
CREATE TYPE instance_health_status AS ENUM ('HEALTHY', 'DEGRADED', 'OFFLINE');
CREATE TYPE detachment_status AS ENUM (
  'REQUESTED',
  'FROZEN',
  'EXPORTED',
  'VERIFIED',
  'TRANSFERRED',
  'CENTRAL_ACCESS_REVOKED',
  'COMPLETED',
  'CANCELLED'
);

COMMIT;

